/**
 * 온라인 결제 UI를 노출할지.
 *
 * `false`인 동안에도 결제 기능 자체는 **그대로 살아 있다** —
 * `/checkout/[id]`, `/orders`, `/api/orders`, 승인·취소·웹훅 모두 동작한다.
 * URL을 직접 아는 사람은 결제할 수 있고, 관리자 화면의 주문 내역도 그대로다.
 * 다만 고객이 사이트를 돌아다니다 마주치는 입구는 만들지 않는다:
 *
 * - 컬렉션 카드의 가격 (ProductCard)
 * - 헤더의 주문 내역 링크 (SiteHeader)
 * - 상세 페이지의 가격·구매 CTA (ProductDetail — 이미 없다)
 *
 * 결제를 열 때 이 값을 `true`로 바꾸면 위 세 곳이 함께 살아난다.
 * (상세 페이지의 CTA만은 마크업이 지워진 상태라 따로 되살려야 한다)
 */
export const SHOW_PAYMENT_UI = false;

/**
 * 소셜 로그인(카카오·네이버) UI를 노출할지.
 *
 * `false`인 동안에도 NextAuth 설정·콜백은 그대로 남아 있다 — 다시 켤 때
 * 버튼만 되살리면 된다. 꺼진 동안은 헤더의 로그인 버튼과 `/login` 화면의
 * 소셜 버튼을 감춘다. 이미 로그인된 세션(관리자 포함)에는 영향 없다.
 */
export const SHOW_SOCIAL_LOGIN = false;
